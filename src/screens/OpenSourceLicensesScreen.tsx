import React, { useState } from 'react';
import { View, Text, TouchableOpacity, SectionList } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useNavigation } from '@react-navigation/native';
import Icon from 'react-native-vector-icons/Feather';
import { useTheme, useThemedStyles } from '../theme';
import type { ThemeColors, ThemeShadows } from '../theme';
import { SPACING, TYPOGRAPHY } from '../constants';
import { BRAND } from '../config/branding';
import notices from '../generated/thirdPartyNotices.json';

type Entry = { title: string; license: string; copyright?: string; note?: string; url?: string; textId?: string; body?: string };

const texts = notices.texts as Record<string, string>;
const fullText = (e: Entry) =>
  e.body ?? [e.copyright, e.note, e.url, e.textId ? texts[e.textId] : undefined].filter(Boolean).join('\n\n');

const SECTIONS: { title: string; data: Entry[] }[] = [
  { title: 'Based on', data: [notices.base] },
  { title: 'Native components and models', data: notices.native },
  { title: `JavaScript packages (${notices.packages.length})`, data: notices.packages },
];

/** Third-party notices (generated by scripts/gen-notices.js). Tap an entry for its full license. */
export const OpenSourceLicensesScreen: React.FC = () => {
  const navigation = useNavigation();
  const { colors } = useTheme();
  const styles = useThemedStyles(createStyles);
  const [open, setOpen] = useState<string | null>(null);

  return (
    <SafeAreaView style={styles.container} edges={['top', 'bottom']}>
      <View style={styles.header}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={styles.backButton}>
          <Icon name="arrow-left" size={20} color={colors.text} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>Open-source licenses</Text>
        <View style={styles.backButton} />
      </View>
      <SectionList
        testID="open-source-licenses"
        sections={SECTIONS}
        keyExtractor={item => item.title}
        contentContainerStyle={styles.content}
        initialNumToRender={20}
        ListHeaderComponent={
          <Text style={styles.intro}>
            {BRAND.name} is built on the open-source software below. Tap an entry to read its license.
          </Text>
        }
        renderSectionHeader={({ section }) => <Text style={styles.sectionTitle}>{section.title}</Text>}
        renderItem={({ item }) => (
          <TouchableOpacity style={styles.row} onPress={() => setOpen(open === item.title ? null : item.title)}>
            <View style={styles.rowHeader}>
              <View style={styles.rowContent}>
                <Text style={styles.rowTitle}>{item.title}</Text>
                <Text style={styles.rowMeta}>{item.license}</Text>
              </View>
              <Icon name={open === item.title ? 'chevron-up' : 'chevron-down'} size={16} color={colors.textMuted} />
            </View>
            {open === item.title && <Text style={styles.licenseText} selectable>{fullText(item)}</Text>}
          </TouchableOpacity>
        )}
      />
    </SafeAreaView>
  );
};

const createStyles = (colors: ThemeColors, shadows: ThemeShadows) => ({
  container: { flex: 1, backgroundColor: colors.background },
  header: {
    flexDirection: 'row' as const,
    alignItems: 'center' as const,
    justifyContent: 'space-between' as const,
    paddingHorizontal: SPACING.lg,
    paddingVertical: SPACING.md,
    minHeight: 60,
    borderBottomWidth: 1,
    borderBottomColor: colors.border,
    backgroundColor: colors.surface,
    ...shadows.small,
    zIndex: 1,
  },
  backButton: { width: 36, padding: SPACING.xs },
  headerTitle: { ...TYPOGRAPHY.h2, color: colors.text },
  content: { paddingHorizontal: SPACING.lg, paddingBottom: SPACING.xxl },
  intro: { ...TYPOGRAPHY.bodySmall, color: colors.textSecondary, paddingVertical: SPACING.lg },
  sectionTitle: {
    ...TYPOGRAPHY.label,
    color: colors.textMuted,
    backgroundColor: colors.background,
    paddingTop: SPACING.lg,
    paddingBottom: SPACING.sm,
  },
  row: {
    backgroundColor: colors.surface,
    borderRadius: 8,
    padding: SPACING.md,
    marginBottom: SPACING.sm,
  },
  rowHeader: { flexDirection: 'row' as const, alignItems: 'center' as const },
  rowContent: { flex: 1 },
  rowTitle: { ...TYPOGRAPHY.body, color: colors.text },
  rowMeta: { ...TYPOGRAPHY.meta, color: colors.textMuted, marginTop: 2 },
  licenseText: { ...TYPOGRAPHY.metaSmall, color: colors.textSecondary, marginTop: SPACING.md },
});
